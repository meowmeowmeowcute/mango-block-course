"""
08 蜂鳴器：嗶一聲
==================================================================
觀念：蜂鳴器用 PWM 控制（PWM 的原理下午講馬達時會詳細說明），今天只要記兩個數字：

  buzzer.freq(頻率)       頻率 = 音高，數字越大聲音越高（例如 440 = La）
  buzzer.duty_u16(音量)   0 = 安靜；3000 左右就夠大聲

  發聲 → 等一下 → 音量設成 0 停止

動手改改看
  1. 把 880 改成 220、2000，聽聽看差在哪裡
  2. 改成「嗶、嗶、嗶」三聲（提示：for 迴圈，中間記得安靜一下）
  3. 按一下 Key1 就嗶一聲（提示：06 的「剛剛被按下」）
  ★ 這個觀念之後會用在 B4 專題的 TODO 3！
"""
import time

from machine import PWM, Pin

buzzer = PWM(Pin("BUZZER"))

try:
    buzzer.freq(1320)        # 音高
    buzzer.duty_u16(3000)   # 開始發聲
    time.sleep(0.3)         # 響 0.3 秒
finally:
    buzzer.duty_u16(0)      # 一定要記得關掉，不然會一直響
