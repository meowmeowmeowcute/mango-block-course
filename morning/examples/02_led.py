"""
02 控制彩燈：一顆、全部、動起來
==================================================================
觀念 1：先設定顏色，再用 write() 送出

  np[編號] = (紅, 綠, 藍)   ← 只是先記下來，燈還不會變
  np.write()               ← 這一行才真的把顏色送到燈上

  - 編號：0 ~ 5（板子上有 6 顆）
  - 顏色：每個數字 0 ~ 255。255 太刺眼，30 左右就夠亮了

觀念 2：6 顆燈用 for 迴圈一顆一顆設定，最後 write() 一次

  for i in range(6):     ← i 會依序是 0, 1, 2, 3, 4, 5
      np[i] = 顏色

觀念 3：動畫 = 一格一格畫（跑馬燈）
  ① 全部關掉 → ② 點亮「現在這一顆」 → ③ write() → ④ 等一下 → 換下一顆，重複

  按 VS Code 狀態列的「Stop」可以停止程式。
  finally 裡的程式「不管怎麼結束都會執行」，用來關燈。

動手改改看
  1. 把第 0 顆改成綠色 (0, 30, 0)；把第一個 np.write() 刪掉，第 0 顆還會先亮嗎？
  2. 讓「偶數號」的燈亮紅色、「奇數號」亮藍色（提示：i % 2 == 0）
  3. 跑馬燈：把 time.sleep(0.1) 改成 0.3、0.03；或改成從第 5 顆往第 0 顆跑（range(5, -1, -1)）
  ★ 這三個觀念都會用在網頁儀表板實作：TODO 1（存顏色）、TODO 4~6（跑馬燈、彩虹、呼吸）！
"""
import time

import neopixel
from machine import Pin

# 6 顆彩燈都接在同一支腳位上，名字叫 "WS2812B"
np = neopixel.NeoPixel(Pin("WS2812B"), 6)

try:
    # --- 觀念 1：點亮一顆 ---
    np[0] = (30, 0, 0)   # 第 0 顆設成紅色
    np.write()           # 送出！
    time.sleep(1)

    # --- 觀念 2：用迴圈設定全部 ---
    for i in range(6):
        np[i] = (0, 0, 30)   # 每一顆都設成藍色
    np.write()               # 6 顆設定完再一次送出
    time.sleep(1)
    # 小提醒：要讓全部同一個顏色，也可以直接寫 np.fill((0, 0, 30))

    # --- 觀念 3：跑馬燈（按 Stop 停止）---
    while True:                     # 一直重複
        for i in range(6):
            np.fill((0, 0, 0))      # ① 全部關掉
            np[i] = (0, 30, 0)      # ② 只點亮第 i 顆
            np.write()              # ③ 送出
            time.sleep(0.1)         # ④ 等 0.1 秒
finally:
    np.fill((0, 0, 0))              # 停止時一定關燈
    np.write()
